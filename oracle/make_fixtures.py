"""Generate cross-language fixtures from the oracle.

The RNG-free cases carry exact expected values and can be checked before the
RNG port is confirmed. The RNG-dependent cases assume test_rng.gd passes; if it
does not, those failures are downstream noise, so run test_rng.gd first.

Run: python3 make_fixtures.py > tests/fixtures/pipeline_fixture.json
"""
import json
import combat
from combat import AttackKind, Combatant, Rng

KIND = {"melee": AttackKind.MELEE, "counter": AttackKind.COUNTER, "ranged": AttackKind.RANGED}
KIND_ORD = {"melee": 0, "counter": 1, "ranged": 2}


def make(**kw):
    c = Combatant()
    for k, v in kw.items():
        if k == "flags":
            c.flags = set(v)
        else:
            setattr(c, k, v)
    return c


CASES = [
    ("healthy melee",            dict(name="a", attack=8, life_base=17, life=17), "melee"),
    ("additive bonus only",      dict(name="a", attack=8, attack_bonus=3, life_base=17, life=17), "melee"),
    ("wounded",                  dict(name="a", attack=8, life_base=17, life=5), "melee"),
    ("wounded + painless",       dict(name="a", attack=8, life_base=17, life=5,
                                      flags=["Не чувствует боли"]), "melee"),
    ("low stamina",              dict(name="a", attack=10, stamina=3, life_base=20, life=20), "melee"),
    ("zero stamina",             dict(name="a", attack=10, stamina=0, life_base=20, life=20), "melee"),
    ("zero stamina + tireless",  dict(name="a", attack=10, stamina=0, life_base=20, life=20,
                                      flags=["Неутомимый"]), "melee"),
    ("all three multipliers",    dict(name="a", attack=12, attack_bonus=2, stamina=2,
                                      life_base=30, life=6, morale=10, morale_base=10), "melee"),
    ("rage suppresses wound",    dict(name="a", attack=12, life_base=30, life=6,
                                      flags=["Боевое безумие"]), "melee"),
    ("counter attack stat",      dict(name="a", counter_attack=6, life_base=17, life=17), "counter"),
    ("ranged attack stat",       dict(name="a", ranged_attack=7, life_base=17, life=17), "ranged"),
]

DEF_CASES = [
    ("plain defence",        dict(name="d", defence=5, ranged_defence=7), "melee"),
    ("plain ranged defence", dict(name="d", defence=5, ranged_defence=7), "ranged"),
    ("defence bonus",        dict(name="d", defence=5, defence_bonus=3), "melee"),
    ("exhausted halving",    dict(name="d", defence=7, ranged_defence=9, stamina=0), "melee"),
    ("exhausted ranged",     dict(name="d", defence=7, ranged_defence=9, stamina=0), "ranged"),
    ("exhausted odd floor",  dict(name="d", defence=1, stamina=0), "melee"),
    ("exhausted tireless",   dict(name="d", defence=7, stamina=0, flags=["Неутомимый"]), "melee"),
]

out = {
    "note": "generated by oracle/make_fixtures.py — do not hand-edit",
    "attack_value": [],
    "defence_value": [],
    "multipliers": {"wound": [], "stamina": []},
    "roll_attack": [],
    "resolve": [],
}

for label, kw, kind in CASES:
    c = make(**kw)
    v, _ = combat.current_attack(c, KIND[kind])
    out["attack_value"].append({
        "label": label, "kind": KIND_ORD[kind], "unit": kw, "expected": round(v, 6),
    })

for label, kw, kind in DEF_CASES:
    c = make(**kw)
    v, _ = combat.current_defence(c, KIND[kind])
    out["defence_value"].append({
        "label": label, "kind": KIND_ORD[kind], "unit": kw, "expected": v,
    })

for pct in (100, 60, 50, 49, 40, 30, 20, 10, 1):
    c = make(life_base=100, life=pct)
    out["multipliers"]["wound"].append({"life": pct, "life_base": 100,
                                        "expected": round(combat.wound_mod(c)[0], 6)})
for st in (10, 6, 5, 4, 3, 2, 1, 0):
    c = make(stamina=st)
    out["multipliers"]["stamina"].append({"stamina": st,
                                          "expected": round(combat.stamina_mod(c)[0], 6)})

# RNG-dependent: exact sequences given a fixed seed
for attack in (1, 3, 5, 8, 13, 37):
    r = Rng(1234)
    out["roll_attack"].append({
        "attack": attack, "seed": 1234,
        "expected": [combat.roll_attack(attack, r)[0] for _ in range(12)],
    })

r = Rng(99)
seq = []
atk = make(name="Мечник", attack=8, attack_bonus=2, life_base=17, life=5, stamina=3)
dfn = make(name="Ополченец", defence=3, life_base=12, life=12)
for _ in range(10):
    d, _tr = combat.resolve_attack(atk, dfn, AttackKind.MELEE, r)
    seq.append(d)
out["resolve"].append({
    "label": "wounded exhausted swordsman vs militia", "seed": 99,
    "attacker": dict(name="Мечник", attack=8, attack_bonus=2, life_base=17, life=5, stamina=3),
    "defender": dict(name="Ополченец", defence=3, life_base=12, life=12),
    "kind": 0, "expected": seq,
})

print(json.dumps(out, ensure_ascii=False, indent=1))
