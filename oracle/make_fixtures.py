"""Generate the cross-language fixtures the GDScript tests consume.

    python3 oracle/make_fixtures.py tests/fixtures/

Writes rng_fixture.json and pipeline_fixture.json.

COMMIT THE OUTPUT. Do not wire this into the test run. A fixture regenerated at
test time records whatever the code currently does, so the test can never fail
and reviews show no diff — the same class of defect as the RNG bug, where every
check passed while the property under test was broken. Regeneration must be a
deliberate act whose diff is reviewable: if a formula changes, the changed
expected values are exactly what a reviewer needs to see.

The RNG-free pipeline cases carry exact expected values and are meaningful
before the RNG port is confirmed. The RNG-dependent cases assume test_rng.gd
passes, so run that first.
"""
